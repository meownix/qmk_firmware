// Use fixed rows and five-character fields on the rotated 32-pixel display.
// Relative newlines leave old text behind when layer labels change length.
static void print_status_narrow(void) {
    static layer_state_t previous_default_layer;
    static layer_state_t previous_layer;
    static uint16_t previous_keymap;
    static uint8_t previous_caps = 2; // Force a complete first draw.
    bool caps = host_keyboard_led_state().caps_lock;
    if (previous_default_layer == default_layer_state && previous_layer == layer_state &&
        previous_keymap == keymap_config.raw && previous_caps == caps) {
        return;
    }
    previous_default_layer = default_layer_state;
    previous_layer = layer_state;
    previous_keymap = keymap_config.raw;
    previous_caps = caps;

    // Rebuild the entire status screen, including every unused row and edge.
    // Only clear on a status change so the OLED can still time out when idle.
    oled_clear();
    oled_set_cursor(0, 2);
    oled_write_P(PSTR("MODE "), false);
    oled_set_cursor(0, 4);
    oled_write_P(keymap_config.swap_lctl_lgui ? PSTR("WIN  ") : PSTR("MAC  "), false);

    oled_set_cursor(0, 5);
    switch (get_highest_layer(default_layer_state)) {
        case _QWERTY:
            oled_write_P(PSTR("Qwrt "), false);
            break;
        case _COLEMAKDH:
            oled_write_P(PSTR("ClDH "), false);
            break;
        case _DVORAK:
            oled_write_P(PSTR("Dvrk "), false);
            break;
        case _MOUSEKEY:
            oled_write_P(PSTR("Mouse"), false);
            break;
        default:
            oled_write_P(PSTR("Undef"), false);
    }

    oled_set_cursor(0, 8);
    oled_write_P(PSTR("LAYER"), false);
    oled_set_cursor(0, 9);
    switch (get_highest_layer(default_layer_state)) {
        case _MOUSEKEY:
            oled_write_P(PSTR("4th  "), false);
            break;
        case _DVORAK:
            oled_write_P(PSTR("3rd  "), false);
            break;
        case _COLEMAKDH:
            oled_write_P(PSTR("2nd  "), false);
            break;
        case _QWERTY:
            oled_write_P(PSTR("Base "), false);
            break;
        default:
            oled_write_P(PSTR("Undef"), false);
    }

    oled_set_cursor(0, 10);
    switch (get_highest_layer(layer_state)) {
        case _RAISE:
            oled_write_P(PSTR("Raise"), false);
            break;
        case _LOWER:
            oled_write_P(PSTR("Lower"), false);
            break;
        case _ADJUST:
            oled_write_P(PSTR("Adj  "), false);
            break;
        default:
            oled_write_P(PSTR("     "), false);
    }

    oled_set_cursor(0, 13);
    oled_write_P(PSTR("CPSLK"), caps);
}

oled_rotation_t oled_init_user(oled_rotation_t rotation) {
    if (is_keyboard_master()) {
        return OLED_ROTATION_270;
    } else {
        return OLED_ROTATION_180; // Flips the display 180 degrees
    }
    return rotation;
}

