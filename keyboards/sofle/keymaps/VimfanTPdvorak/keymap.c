bool detect_key_down(void) {
    // Keep one bit per key instead of two 100-entry coordinate caches.
    static matrix_row_t previous_rows[MATRIX_ROWS];
    bool pressed = false;
    for (uint8_t row = 0; row < MATRIX_ROWS; ++row) {
        matrix_row_t current = matrix_get_row(row);
        pressed |= (current & ~previous_rows[row]) != 0;
        previous_rows[row] = current;
    }
    return pressed;
}

void eval_anim_state(void) {
    key_down = detect_key_down();

    switch (anim_state)
    {
        case Idle:
            if (key_down) // Idle to Tap
            {
                anim_state = Tap;
            }
            break;

        case Prep:
            if (key_down) // Prep to Tap
            {
                anim_state = Tap;
            }
            else if (timer_elapsed32(idle_timeout_timer) >= IDLE_TIMEOUT) // Prep to Idle
            {
                anim_state = Idle;
                current_idle_frame = 0;
            }
            break;

        case Tap:
            if (!key_down) // Tap to Prep
            {
                anim_state = Prep;
                idle_timeout_timer = timer_read32();
            }
            break;

        default:
            break;
    }
}

static void draw_bongo_or_render_logo(bool minimal) {
    eval_anim_state();

    oled_set_cursor(0, 0);

    if (get_current_wpm() == 0) {
        // Clear once on the animation-to-logo transition, including the two
        // edge columns that text spaces cannot reach. Repeated clears would
        // keep the display dirty and prevent the normal idle timeout.
        if (!oled_cleared) {
            oled_clear();
            oled_cleared = true;
        }
        oled_write_P(qmk_logo, false);
    } else {
        oled_cleared = false;
        switch (anim_state) {
            case Idle:
                if (minimal)
                    oled_write_raw_P(idle_minimal[abs((IDLE_FRAMES - 1) - current_idle_frame)], ANIM_SIZE);
                else
                    oled_write_raw_P(idle[abs((IDLE_FRAMES - 1) - current_idle_frame)], ANIM_SIZE);

                if (timer_elapsed32(anim_timer) > ANIM_FRAME_DURATION)
                {
                    current_idle_frame = (current_idle_frame + 1) % IDLE_FRAMES;
                    anim_timer = timer_read32();
                }
                break;

            case Prep:
                if (minimal)
                    oled_write_raw_P(prep_minimal[0], ANIM_SIZE);
                else
                    oled_write_raw_P(prep[0], ANIM_SIZE);
                break;

            case Tap:
                if (minimal)
                    oled_write_raw_P(tap_minimal[abs((TAP_FRAMES - 1) - current_tap_frame)], ANIM_SIZE);
                else
                    oled_write_raw_P(tap[abs((TAP_FRAMES - 1) - current_tap_frame)], ANIM_SIZE);
                current_tap_frame = (current_tap_frame + 1) % TAP_FRAMES;
                break;

            default:
                break;
        }

        if (!minimal) {
            // print wpm
            oled_set_cursor(0, 0);
            oled_write_P(PSTR("WPM: "), false);
            oled_write(get_u8_str(get_current_wpm(), '0'), false);
        }
    }
}

bool oled_task_user(void) {
    if (is_keyboard_master()) {
        print_status_narrow();
    } else {
        draw_bongo_or_render_logo(false);
    }
    return false;
}

